import { createRequire } from "node:module";
import { homedir } from "node:os";
import { delimiter, dirname, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const directory = dirname(fileURLToPath(import.meta.url));
const nodePaths = [
  resolve(directory, "../node_modules"),
  ...(process.env.NODE_PATH || "").split(delimiter).filter(Boolean),
  resolve(homedir(), ".hermes/hermes-agent/node_modules"),
];
const require = createRequire(import.meta.url);
const { build } = require(require.resolve("esbuild", { paths: nodePaths }));

// Resolve every bare import inside the configured package roots only. esbuild's normal lookup
// also searches ancestor node_modules folders (e.g. ~/node_modules), which can silently bundle a
// different or duplicate React; results outside the root being tried are therefore rejected.
const pinnedPackages = {
  name: "pinned-packages",
  setup(builder) {
    builder.onResolve({ filter: /^[^./]/ }, async ({ path, kind, pluginData }) => {
      if (pluginData === "pinned") return undefined;
      for (const root of nodePaths) {
        const result = await builder.resolve(path, {
          kind,
          resolveDir: dirname(root),
          pluginData: "pinned",
        });
        if (result.errors.length === 0 && result.path.startsWith(root + sep)) {
          return { path: result.path };
        }
      }
      return { errors: [{ text: `${path} is not installed in ${nodePaths.join(", ")}` }] };
    });
  },
};

await build({
  entryPoints: [resolve(directory, "src/main.tsx")],
  outfile: resolve(directory, "dist/app.js"),
  bundle: true,
  format: "esm",
  jsx: "automatic",
  define: { "process.env.NODE_ENV": '"production"' },
  minify: true,
  target: "es2023",
  nodePaths,
  plugins: [pinnedPackages],
  banner: { js: "// Generated by `make web` from web/src; do not edit" },
  legalComments: "inline",
  write: !process.argv.includes("--check"),
});
